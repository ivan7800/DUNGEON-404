'use strict';
const assert=require('node:assert/strict');
const engine=require('../engine.js');
const rand=()=>.5;
assert.equal(engine.VERSION,16);
assert.notDeepEqual(engine.LABYRINTH,engine.LOWER);
assert(engine.LABYRINTH.filter((r,i)=>r!==engine.LOWER[i]).length>=5,'Third floor must be geometrically different');
const s=engine.createGame();
s.selected=2;s.x=4;s.y=3;s.dir=1;
const mon=s.monsters.find(m=>m.floor===1 && m.kind==='lurker');
assert.equal(mon.x,5);assert.equal(mon.y,3);
let mana=s.party[2].mana;
engine.dispatch(s,'frost',rand);
assert.equal(s.party[2].mana,mana-7);
assert(mon.hp<mon.max);assert.equal(mon.frozen,1);
const still=[mon.x,mon.y];
engine.dispatch(s,'guard',rand);
assert.equal(mon.frozen,0);assert.deepEqual([mon.x,mon.y],still);
const t=engine.createGame();t.selected=0;const before=t.turn;
engine.dispatch(t,'frost',rand);assert.equal(t.turn,before,'non-caster cannot waste a turn');
const old=engine.createGame();old.schema=8;old.floor=3;old.x=6;old.y=8;old.visited=['6,8'];old.visitedByFloor[3]=['6,8'];
const migrated=engine.importSave(old);
assert(migrated,'v8 migration must succeed');assert.equal(migrated.schema,16);
assert(engine.passable(migrated.x,migrated.y,3,migrated));
assert(engine.validGame(migrated));
console.log('OK v0.9: distinct third map, frost mana/damage/turns, v8 migration');
