'use strict';
const assert=require('node:assert/strict');
const core=require('../engine.js');
assert.equal(core.VERSION,16);
let s=core.createGame();
assert(core.validGame(s));
assert.equal(Object.keys(core.GEAR).length,6);
s.floor=4;s.x=1;s.y=4;s.dir=2;
core.dispatch(s,'forward',()=>.5);
assert(s.gear.includes('daggers'));
assert(s.gearFound.includes('4:1,5'));
const original=s.gear.length;
s.x=1;s.y=4;core.dispatch(s,'forward',()=>.5);
assert.equal(s.gear.length,original,'equipment cannot duplicate');
s.selected=1;core.dispatch(s,'equip:daggers');
assert.equal(s.party[1].equippedWeapon,'daggers');
assert(core.validGame(s));
s.selected=0;core.dispatch(s,'equip:daggers');
assert.equal(s.party[0].equippedWeapon,undefined,'only rogues can use daggers');
s.selected=1;core.dispatch(s,'unequipWeapon');
assert.equal(s.party[1].equippedWeapon,undefined);
assert(core.validGame(s));
s.x=8;s.y=7;s.dir=1;core.dispatch(s,'forward',()=>.5);
assert(s.gear.includes('bulwark'));
s.selected=0;core.dispatch(s,'equip:bulwark');
assert.equal(s.party[0].equippedArmor,'bulwark');
assert(core.validGame(s));
const dup=JSON.parse(JSON.stringify(s));dup.party[1].equippedArmor='bulwark';
assert.equal(core.validGame(dup),false,'invalid class gear rejected');
const s15=core.createGame();s15.schema=15;
const migrated=core.importSave(s15);
assert(migrated&&migrated.schema===16&&core.validGame(migrated));
console.log('OK v1.6: loot, class limitations, unequip, validation, migration');
