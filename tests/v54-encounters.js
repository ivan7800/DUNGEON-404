'use strict';
const assert=require('node:assert/strict');
const C=require('../engine.js');
const rng=()=>.5;
const s=C.createGame();
s.floor=1;s.x=5;s.y=7;s.dir=1;
const star=s.monsters.find(m=>m.kind==='starseer');
star.x=7;star.y=7;
const hp=()=>s.party.reduce((n,p)=>n+p.hp,0);
const before=hp();
const warning=C.dispatch(s,'guard',rng);
assert.equal(star.telegraph,true,'the creature must visibly warn before its strike');
assert.equal(hp(),before,'a telegraph turn must not deal damage');
assert(warning.some(e=>/estrellas se alinean/.test(e.text)));
const save=C.importSave(JSON.parse(JSON.stringify(s)));
assert(save&&save.monsters.find(m=>m.kind==='starseer').telegraph===true,'telegraph must survive save/load');
const strike=C.dispatch(save,'guard',rng);
assert.equal(save.monsters.find(m=>m.kind==='starseer').telegraph,false,'the warning must resolve once');
assert(save.party.reduce((n,p)=>n+p.hp,0)<before,'the warned strike should resolve on the next turn');
assert(strike.some(e=>/fulmina/.test(e.text)));
const frozen=C.createGame();frozen.floor=1;frozen.x=5;frozen.y=7;
const moth=frozen.monsters.find(m=>m.kind==='voidmoth');moth.x=7;moth.y=7;moth.frozen=1;
C.dispatch(frozen,'guard',rng);
assert.equal(moth.telegraph,undefined,'freezing interrupts an unstarted cosmic warning');
assert(C.validGame(C.importSave(JSON.parse(JSON.stringify(save)))));
console.log('v5.4 encounter telegraph, save persistence and interruption checks passed');
